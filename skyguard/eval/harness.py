"""Ablation harness: every detector on the same injected data, same seed.

The point is not that the final row wins — it is to show how much each layer
contributes, and to be honest where a layer adds little. Every comparison
fixes the data (simulator seed), the injection (injector seed) and the splits,
so rows differ only in the detector. Numbers printed here are regenerated by
running the harness, never hand-copied.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import datetime
from typing import Dict, List, Sequence

import numpy as np

from ..types import Observation
from .metrics import (
    event_recall,
    expected_calibration_error,
    genuine_extreme_far,
    per_class_recall,
    point_metrics,
    spans_from_labels,
)

# Binary verdict cut on calibrated [0, 1] detector scores.
DECISION_THRESHOLD = 0.5


@dataclass
class DetectorReport:
    """One detector's full scorecard on one test slice."""

    name: str
    point: Dict[str, float] = field(default_factory=dict)
    event: Dict[str, object] = field(default_factory=dict)
    per_class: Dict[str, float] = field(default_factory=dict)
    genuine_extreme_far: float = 0.0
    ece: float = float("nan")

    def headline(self) -> str:
        """One comparable line: F1, false alarms, event recall, weather FAR."""
        return (
            f"{self.name:<22} F1={self.point.get('f1', float('nan')):.3f} "
            f"FAR={self.point.get('false_alarm_rate', float('nan')):.4f} "
            f"event_recall={self.event.get('event_recall', float('nan')):.3f} "
            f"genuine_FAR={self.genuine_extreme_far:.4f} "
            f"ECE={self.ece:.4f}"
        )


def compare(
    detectors: Dict[str, object],
    levels: np.ndarray,
    y_true: np.ndarray,
    class_values: np.ndarray,
    timestamps: Sequence[datetime] | None = None,
) -> List[DetectorReport]:
    """Score every detector on the same (N, 3) test levels and boolean truth.

    Each detector exposes `score_points(levels) -> (N,) [0, 1]`; stateful
    detectors (rules) additionally offer `score_series(timestamps, levels)`,
    which is preferred whenever timestamps are provided. Verdicts cut at 0.5.
    Genuine-extreme points count as normal everywhere except their own
    dedicated false-alarm metric.
    """
    mat = np.asarray(levels, dtype=np.float64)
    truth = np.asarray(y_true, dtype=bool).ravel()
    reports: List[DetectorReport] = []
    for name, detector in detectors.items():
        if timestamps is not None and hasattr(detector, "score_series"):
            scores = np.asarray(detector.score_series(timestamps, mat), dtype=np.float64).ravel()  # type: ignore[union-attr]
        else:
            scores = np.asarray(detector.score_points(mat), dtype=np.float64).ravel()  # type: ignore[union-attr]
        pred = scores >= DECISION_THRESHOLD
        clean_truth = truth & (np.asarray(class_values, dtype=object).ravel() != "genuine_extreme")
        reports.append(DetectorReport(
            name=name,
            point=point_metrics(clean_truth, pred),
            event=event_recall(spans_from_labels(clean_truth), pred),
            per_class=per_class_recall(class_values, pred),
            genuine_extreme_far=genuine_extreme_far(class_values, pred),
            ece=float(expected_calibration_error(scores, clean_truth)["ece"]),
        ))
    return reports


def format_table(reports: Sequence[DetectorReport]) -> str:
    """Aligned scoreboard for logs and the README."""
    return "\n".join(report.headline() for report in reports)


class RulesBaseline:
    """Rule-only detector: the traditional-QC row of the ablation ladder.

    Streams timestamped levels through Layer 1; the score is the rule verdict.
    NaN levels become missing values (never silent zeros — that would invent
    perfect 0.0 observations out of outages).
    """

    def __init__(self, station_id: str = "HARNESS", interval_minutes: int = 60) -> None:
        from ..qc.rules import RuleEngine

        self.station_id = station_id
        self.engine = RuleEngine(interval_minutes=interval_minutes)

    def score_series(
        self, timestamps: Sequence[datetime], levels: np.ndarray
    ) -> np.ndarray:
        """Score a timestamped (N, 3) slice in stream order."""
        mat = np.asarray(levels, dtype=np.float64)
        out = np.empty(mat.shape[0], dtype=np.float64)
        for i, ts in enumerate(timestamps):
            triple = [None if math.isnan(v) else float(v) for v in mat[i]]
            obs = Observation(self.station_id, ts, triple[0], triple[1], triple[2])
            out[i] = self.engine.evaluate(obs).score
        return out

    def score_points(self, levels: np.ndarray) -> np.ndarray:
        """Untimestamped scoring is meaningless for stateful rules — use
        `score_series`. This exists only to satisfy the detector protocol."""
        raise NotImplementedError("RulesBaseline needs timestamps: use score_series")
